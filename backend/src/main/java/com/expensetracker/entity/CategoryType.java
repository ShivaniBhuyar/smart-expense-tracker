package com.expensetracker.entity;

/**
 * Enumeration defining financial classification types for transaction categories.
 * 
 * INCOME: Indicates categories representing incoming revenue (Salary, Freelance, Investments, etc.).
 * EXPENSE: Indicates categories representing outgoing expenditures (Food, Rent, Utilities, Entertainment, etc.).
 */
public enum CategoryType {
    INCOME,
    EXPENSE
}
